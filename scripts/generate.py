@dataclass
class FieldInfo:
    name: str
    schema: dict[str, Any]
    required: bool


def _is_nullable(schema: dict[str, Any]) -> bool:
    """True when JSON Schema allows JSON null (not merely omitting the key)."""
    types = schema.get("type")
    if types == "null" or (isinstance(types, list) and "null" in types):
        return True
    for key in ("anyOf", "oneOf"):
        for sub in schema.get(key, []):
            if isinstance(sub, dict) and sub.get("type") == "null":
                return True
    return False


def _annotation_includes_none(annotation: str) -> bool:
    return annotation == "None" or annotation.endswith("| None") or "| None |" in annotation


def _object_fields(schema: dict[str, Any]) -> list[FieldInfo] | None:
    if schema.get("type") != "object" or "properties" not in schema:
        return None
    required = set(schema.get("required", []))
    fields = []
    for name, subschema in schema["properties"].items():
        fields.append(FieldInfo(name=name, schema=subschema, required=name in required))
    return fields


def _required_any_of_groups(schema: dict[str, Any]) -> tuple[tuple[str, ...], ...]:
    """Return supported object-level ``anyOf`` required-property groups."""
    groups: list[tuple[str, ...]] = []
    for variant in schema.get("anyOf", []):
        if set(variant) != {"required"} or not isinstance(variant["required"], list):
            raise ValueError(f"unsupported object anyOf variant: {variant!r}")
        required = tuple(variant["required"])
        if not required or not all(isinstance(name, str) for name in required):
            raise ValueError(f"invalid object anyOf required group: {variant!r}")
        groups.append(required)
    return tuple(groups)


def _def_sort_key(item: tuple[str, dict[str, Any]]) -> tuple[int, str]:
    """Emit enums first so objects can reference them; otherwise alphabetical."""
    name, schema = item
    kind = 0 if schema.get("enum") or "const" in schema else 1
    return (kind, name)


