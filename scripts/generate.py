#!/usr/bin/env python3
"""Deterministic code generators for canonical schemas.

Currently registered generators:

- ``ts``      TypeScript types from all document schemas into
              ``packages/typescript/document-model/src/generated/``.
- ``pydantic`` Pydantic models from all document schemas into
              ``packages/python/document-model/src/document_model/generated/``.

Generated output must never be edited by hand; freshness is enforced by
``just generate-check``.
"""

from __future__ import annotations

import json
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from repo import ROOT

SCHEMA_ROOT = ROOT / "schemas"
DOCUMENT_SCHEMAS = (
    "common",
    "physical-document",
    "evidence",
    "layout-document",
    "semantic-document",
    "mapping",
)

TS_OUT = ROOT / "packages/typescript/document-model/src/generated"
PY_OUT = ROOT / "packages/python/document-model/src/document_model/generated"

TS_HEADER = "// Generated by scripts/generate.py from schemas/. DO NOT EDIT.\n"

PY_HEADER = "# Generated by scripts/generate.py from schemas/. DO NOT EDIT.\n"


@dataclass
class SchemaSet:
    """Loaded schemas plus a ref resolver across the set."""

    schemas: dict[str, dict[str, Any]]

    def resolve_ref(self, ref: str) -> tuple[str, str]:
        """Return (schema_name, def_name) for a canonical or relative ref."""
        base, _, pointer = ref.partition("#")
        tail = (
            base.split("/schemas/", 1)[-1]
            if "/schemas/" in base
            else base.replace("../", "").strip("/")
        )
        name = tail.split("/", 1)[0]
        pointer = pointer.removeprefix("/$defs/")
        return name, pointer


def load_schemas() -> SchemaSet:
    schemas: dict[str, dict[str, Any]] = {}
    for name in DOCUMENT_SCHEMAS:
        path = SCHEMA_ROOT / name / "schema.json"
        schemas[name] = json.loads(path.read_text(encoding="utf-8"))
    return SchemaSet(schemas=schemas)


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.replace("-", "_").split("_"))


def snake(name: str) -> str:
    return name.replace("-", "_")


def _resolve_def_ref(schema_set: SchemaSet, schema_name: str, ref: str) -> tuple[str, str]:
    """Resolve a $ref that may be intra-document ("#/$defs/X") or cross-document."""
    if ref.startswith("#/"):
        pointer = ref.removeprefix("#/$defs/")
        if pointer == ref:
            raise ValueError(f"unsupported intra-document ref pointer: {ref!r}")
        return schema_name, pointer
    return schema_set.resolve_ref(ref)


def _union_variants(
    schema_set: SchemaSet, schema_name: str, schema: dict[str, Any]
) -> list[tuple[str, str]]:
    """Variant (schema_name, def_name) pairs of a oneOf union of $refs."""
    variants: list[tuple[str, str]] = []
    for ref in schema.get("oneOf", []):
        if not isinstance(ref, dict) or "$ref" not in ref:
            raise ValueError(f"union with unsupported variant: {ref!r} in {schema_name}")
        variants.append(_resolve_def_ref(schema_set, schema_name, ref["$ref"]))
    return variants


def _dedupe(values: list[str]) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for value in values:
        if value not in seen:
            seen.add(value)
            out.append(value)
    return out


