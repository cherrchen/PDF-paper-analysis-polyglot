#!/usr/bin/env python3
"""Deterministic code generators for canonical schemas.

Currently registered generators:

- ``ts``      TypeScript types from all document schemas into
              ``packages/typescript/document-model/src/generated/``.
- ``pydantic`` Pydantic models from all document schemas into
              ``packages/python/document-model/src/document_model/generated/``.

Generated output must never be edited by hand; freshness is enforced by
``just generate-check``. ``just generate`` Ruff-formats the Pydantic module
after writing it so the committed file matches ``just fmt``.
"""

from __future__ import annotations

import json
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, cast

sys.path.insert(0, str(Path(__file__).resolve().parent))
from repo import ROOT

SCHEMA_ROOT = ROOT / "schemas"
DOCUMENT_SCHEMAS = (
    "common",
    "physical-document",
    "evidence",
    "layout-document",
    "semantic-document",
    "mapping",
)

TS_OUT = ROOT / "packages/typescript/document-model/src/generated"
PY_OUT = ROOT / "packages/python/document-model/src/document_model/generated"

TS_HEADER = "// Generated by scripts/generate.py from schemas/. DO NOT EDIT.\n"

PY_HEADER = "# Generated by scripts/generate.py from schemas/. DO NOT EDIT.\n"

PY_PREAMBLE = """from __future__ import annotations

from typing import Annotated, Any, ClassVar, Literal, cast

from pydantic import BaseModel, BeforeValidator, ConfigDict, Field, model_validator
from pydantic_core import PydanticCustomError

# All $defs names are globally unique across the canonical schemas, so
# this module is a flat namespace. Extra keys are forbidden everywhere
# except SemanticNode.attributes, which mirrors the open attribute bag.


def _json_integer(value: object) -> int:
    # JSON Schema accepts integral JSON numbers such as 2.0 as integers,
    # while rejecting booleans and strings that Pydantic would coerce.
    if isinstance(value, bool):
        raise PydanticCustomError("json_integer", "expected a JSON integer")
    if isinstance(value, int):
        return value
    if isinstance(value, float) and value.is_integer():
        return int(value)
    raise PydanticCustomError("json_integer", "expected a JSON integer")


def _reject_boolean_number(value: object) -> object:
    # Python equality conflates False/0 and True/1; JSON Schema does not.
    if isinstance(value, bool):
        raise PydanticCustomError("json_number", "expected a JSON number, not a boolean")
    return value


JsonInteger = Annotated[int, BeforeValidator(_json_integer)]


class _CanonicalModel(BaseModel):
    model_config = ConfigDict(strict=True, allow_inf_nan=False)
    __non_nullable_optional_fields__: ClassVar[frozenset[str]] = frozenset()
    __required_any_of__: ClassVar[tuple[frozenset[str], ...]] = ()

    @model_validator(mode="before")
    @classmethod
    def _validate_json_object(cls, value: object) -> object:
        if not isinstance(value, dict):
            return value
        data = cast("dict[str, object]", value)
        null_fields = cls.__non_nullable_optional_fields__.intersection(
            key for key, item in data.items() if item is None
        )
        if null_fields:
            names = ", ".join(sorted(null_fields))
            raise ValueError(f"explicit null is not allowed for: {names}")
        if cls.__required_any_of__ and not any(
            all(name in data for name in group) for group in cls.__required_any_of__
        ):
            choices = ", ".join("+".join(sorted(group)) for group in cls.__required_any_of__)
            raise ValueError(
                f"at least one required-property group must be present: {choices}"
            )
        return data
"""


@dataclass
class SchemaSet:
    """Loaded schemas plus a ref resolver across the set."""

    schemas: dict[str, dict[str, Any]]

    def resolve_ref(self, ref: str) -> tuple[str, str]:
        """Return (schema_name, def_name) for a canonical or relative ref."""
        base, _, pointer = ref.partition("#")
        tail = (
            base.split("/schemas/", 1)[-1]
            if "/schemas/" in base
            else base.replace("../", "").strip("/")
        )
        name = tail.split("/", 1)[0]
        pointer = pointer.removeprefix("/$defs/")
        return name, pointer


def load_schemas() -> SchemaSet:
    schemas: dict[str, dict[str, Any]] = {}
    for name in DOCUMENT_SCHEMAS:
        path = SCHEMA_ROOT / name / "schema.json"
        schemas[name] = json.loads(path.read_text(encoding="utf-8"))
    return SchemaSet(schemas=schemas)


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.replace("-", "_").split("_"))


def snake(name: str) -> str:
    return name.replace("-", "_")


def _resolve_def_ref(schema_set: SchemaSet, schema_name: str, ref: str) -> tuple[str, str]:
    """Resolve a $ref that may be intra-document ("#/$defs/X") or cross-document."""
    if ref.startswith("#/"):
        pointer = ref.removeprefix("#/$defs/")
        if pointer == ref:
            raise ValueError(f"unsupported intra-document ref pointer: {ref!r}")
        return schema_name, pointer
    return schema_set.resolve_ref(ref)


def _union_variants(
    schema_set: SchemaSet, schema_name: str, schema: dict[str, Any]
) -> list[tuple[str, str]]:
    """Variant (schema_name, def_name) pairs of a oneOf union of $refs."""
    variants: list[tuple[str, str]] = []
    for ref in schema.get("oneOf", []):
        if not isinstance(ref, dict) or "$ref" not in ref:
            raise ValueError(f"union with unsupported variant: {ref!r} in {schema_name}")
        variants.append(_resolve_def_ref(schema_set, schema_name, ref["$ref"]))
    return variants


def _dedupe(values: list[str]) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for value in values:
        if value not in seen:
            seen.add(value)
            out.append(value)
    return out


