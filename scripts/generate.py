GENERATORS: dict[str, Any] = {
    "ts": ("packages/typescript/document-model/src/generated/schema.ts", generate_ts),
    "pydantic": (
        "packages/python/document-model/src/document_model/generated/schema_models.py",
        generate_pydantic,
    ),
}


def _format_python(content: str, source_path: Path) -> str:
    """Ruff-format generated Python so freshness checks match ``just fmt``.

    ``--stdin-filename`` keeps Ruff's config discovery on the real output
    path (line length, excludes) instead of a temporary file under ``/tmp``.
    """
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "format",
            "--stdin-filename",
            str(source_path),
            "-",
        ],
        check=True,
        capture_output=True,
        text=True,
        input=content,
        cwd=ROOT,
    )
    formatted: str = result.stdout
    return formatted


def main() -> int:
    schema_set = load_schemas()
    only = sys.argv[1] if len(sys.argv) > 1 else None
    names = [only] if only in GENERATORS else list(GENERATORS)
    for name in names:
        rel_path, func = GENERATORS[name]
        out_path = ROOT / rel_path
        out_path.parent.mkdir(parents=True, exist_ok=True)
        content = func(schema_set)
        if name == "pydantic":
            content = _format_python(content, out_path)
        previous = out_path.read_text(encoding="utf-8") if out_path.is_file() else None
        if previous != content:
            out_path.write_text(content, encoding="utf-8")
            print(f"generated {rel_path}")
        else:
            print(f"up-to-date {rel_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
