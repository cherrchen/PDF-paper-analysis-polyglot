# shared type analysis
# ---------------------------------------------------------------------------


@dataclass
class FieldInfo:
    name: str
    schema: dict[str, Any]
    required: bool


def _object_fields(schema: dict[str, Any]) -> list[FieldInfo] | None:
    if schema.get("type") != "object" or "properties" not in schema:
        return None
    required = set(schema.get("required", []))
    fields = []
    for name, subschema in schema["properties"].items():
        fields.append(FieldInfo(name=name, schema=subschema, required=name in required))
    return fields


def _def_sort_key(item: tuple[str, dict[str, Any]]) -> tuple[int, str]:
    """Emit enums first so objects can reference them; otherwise alphabetical."""
    name, schema = item
    kind = 0 if schema.get("enum") or "const" in schema else 1
    return (kind, name)


