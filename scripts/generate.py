class PydanticGenerator:
    """Generates a flat Pydantic module from the canonical schemas.

    All ``$defs`` names are globally unique across the six schemas, so defs
    are emitted at module level. oneOf unions become plain union aliases;
    tagged variants keep their Literal discriminator fields.
    """

    def __init__(self, schema_set: SchemaSet) -> None:
        self.set = schema_set

    # -- annotations ----------------------------------------------------------

    def annotation(self, schema_name: str, schema: dict[str, Any]) -> str:  # noqa: PLR0911
        if "$ref" in schema:
            _, def_name = _resolve_def_ref(self.set, schema_name, schema["$ref"])
            return pascal(def_name)
        if "oneOf" in schema:
            rendered = [
                self.annotation(target_name, {"$ref": f"#/$defs/{def_name}"})
                for target_name, def_name in _union_variants(self.set, schema_name, schema)
            ]
            return " | ".join(_dedupe(rendered))
        if "anyOf" in schema:
            rendered = []
            for sub in schema["anyOf"]:
                if "$ref" in sub:
                    _, def_name = _resolve_def_ref(self.set, schema_name, sub["$ref"])
                    rendered.append(pascal(def_name))
                elif "enum" in sub or "const" in sub or "type" in sub:
                    rendered.append(self.annotation(schema_name, sub))
                else:
                    raise ValueError(f"unsupported anyOf variant: {json.dumps(sub)[:200]}")
            return " | ".join(_dedupe(rendered))
        if "enum" in schema:
            values = ", ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
            return f"Literal[{values}]"
        if "const" in schema:
            value = schema["const"]
            return f"Literal[{json.dumps(value, ensure_ascii=False)}]"
        types = schema.get("type")
        if isinstance(types, list):
            return " | ".join(self._primitive(t) for t in types)
        if isinstance(types, str):
            if types == "array":
                items = schema.get("items")
                if isinstance(items, dict):
                    return f"list[{self.annotation(schema_name, items)}]"
                return "list[Any]"
            if types == "object" and "properties" not in schema:
                return "dict[str, Any]"
            return self._primitive(types)
        raise ValueError(f"cannot render annotation for: {json.dumps(schema)[:200]}")

    @staticmethod
    def _primitive(type_name: str) -> str:
        return {
            "string": "str",
            "number": "float",
            "integer": "JsonInteger",
            "boolean": "bool",
            "array": "list[Any]",
            "object": "dict[str, Any]",
            "null": "None",
        }.get(type_name, "Any")

    # -- emission ---------------------------------------------------------------

    def emit(self) -> str:
        out = cast("list[str]", (PY_HEADER + "\n" + PY_PREAMBLE).splitlines())
        for schema_name in DOCUMENT_SCHEMAS:
            schema = self.set.schemas[schema_name]
            defs = schema.get("$defs", {})
            out.append(f"# --- {schema_name} " + "-" * max(1, 56 - len(schema_name)))
            out.append("")
            # First pass: object classes (they may be referenced by aliases).
            # Document schemas also expose their root object as a model.
            roots: list[tuple[str, dict[str, Any]]] = []
            if schema.get("type") == "object" and "properties" in schema:
                roots.append((schema["title"], schema))
            for def_name, def_schema in sorted(defs.items(), key=_def_sort_key):
                if _object_fields(def_schema) is not None:
                    out.extend(self._emit_def(schema_name, def_name, def_schema))
            for root_name, root_schema in roots:
                out.extend(self._emit_def(schema_name, root_name, root_schema))
            # Second pass: aliases (enums, ids, unions, constrained primitives).
            for def_name, def_schema in sorted(defs.items(), key=_def_sort_key):
                if _object_fields(def_schema) is None:
                    out.extend(self._emit_def(schema_name, def_name, def_schema))
        return "\n".join(out).rstrip() + "\n"

    def _emit_def(  # noqa: PLR0911
        self, schema_name: str, def_name: str, schema: dict[str, Any]
    ) -> list[str]:
        name = pascal(def_name)
        doc = schema.get("description")
        doc_line = f"# {doc}" if doc else None
        if "const" in schema:
            literal = json.dumps(schema["const"], ensure_ascii=False)
            return self._alias(name, literal, doc_line)
        if "enum" in schema:
            values = ", ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
            literal = f"Literal[{values}]"
            has_numeric = any(
                isinstance(value, (int, float)) and not isinstance(value, bool)
                for value in schema["enum"]
            )
            has_boolean = any(isinstance(value, bool) for value in schema["enum"])
            if has_numeric and has_boolean:
                raise ValueError(f"mixed Boolean/numeric enum is unsupported: {name}")
            if has_numeric:
                literal = f"Annotated[{literal}, BeforeValidator(_reject_boolean_number)]"
            return self._alias(name, literal, doc_line)
        if "oneOf" in schema:
            rendered = [
                pascal(variant_def)
                for _, variant_def in _union_variants(self.set, schema_name, schema)
            ]
            return self._alias(name, " | ".join(_dedupe(rendered)), doc_line)
        fields = _object_fields(schema)
        if fields is None:
            ann = self.annotation(schema_name, schema)
            constraints = self._constraint_parts(schema)
            if constraints:
                return self._alias(
                    name, f"Annotated[{ann}, Field({', '.join(constraints)})]", doc_line
                )
            return self._alias(name, ann, doc_line)

        lines: list[str] = [f"class {name}(_CanonicalModel):"]
        if doc_line:
            lines.append(f"    {doc_line}")
        allow_extra = schema_name == "semantic-document" and def_name == "SemanticNode"
        extra = 'extra="allow"' if allow_extra else 'extra="forbid"'
        lines.append(f"    model_config = ConfigDict({extra}, strict=True, allow_inf_nan=False)")
        non_nullable_optional = frozenset(
            field.name for field in fields if not field.required and not _is_nullable(field.schema)
        )
        if non_nullable_optional:
            rendered = ", ".join(repr(item) for item in sorted(non_nullable_optional))
            lines.append(
                "    __non_nullable_optional_fields__: ClassVar[frozenset[str]] = "
                f"frozenset({{{rendered}}})"
            )
        required_any_of = _required_any_of_groups(schema)
        if required_any_of:
            rendered_groups = ", ".join(
                f"frozenset({{{', '.join(repr(item) for item in group)}}})"
                for group in required_any_of
            )
            if len(required_any_of) == 1:
                rendered_groups += ","
            lines.append(
                "    __required_any_of__: ClassVar[tuple[frozenset[str], ...]] = "
                f"({rendered_groups})"
            )
        if not fields:
            lines.append("    pass")
            lines.append("")
            return lines
        for field in fields:
            lines.append(self._field_line(schema_name, field))
        lines.append("")
        return lines

    def _field_line(self, schema_name: str, field: FieldInfo) -> str:
        """Render one model field.

        JSON Schema optional means the key may be omitted, not that JSON null
        is allowed. Null is only accepted when the schema itself is nullable
        (``type: null`` or ``anyOf``/``oneOf`` including null).
        """
        fname = field.name
        ann = self.annotation(schema_name, field.schema)
        constraints = self._constraint_parts(field.schema)
        if not field.required and not _annotation_includes_none(ann):
            ann = f"{ann} | None"
        args: list[str] = []
        if not field.required:
            args.append("default=None")
        args.extend(constraints)
        if args:
            return f"    {fname}: {ann} = Field({', '.join(args)})"
        return f"    {fname}: {ann}"

    @staticmethod
    def _alias(name: str, value: str, doc_line: str | None) -> list[str]:
        lines = []
        if doc_line:
            lines.append(doc_line)
        lines.append(f"{name} = {value}")
        lines.append("")
        return lines

    @staticmethod
    def _constraint_parts(schema: dict[str, Any]) -> list[str]:
        parts: list[str] = []
        if schema.get("minimum") is not None:
            parts.append(f"ge={schema['minimum']}")
        if schema.get("maximum") is not None:
            parts.append(f"le={schema['maximum']}")
        if schema.get("exclusiveMinimum") is not None:
            parts.append(f"gt={schema['exclusiveMinimum']}")
        if schema.get("exclusiveMaximum") is not None:
            parts.append(f"lt={schema['exclusiveMaximum']}")
        if schema.get("minItems") is not None:
            parts.append(f"min_length={schema['minItems']}")
        if schema.get("maxItems") is not None:
            parts.append(f"max_length={schema['maxItems']}")
        if schema.get("minLength") is not None:
            parts.append(f"min_length={schema['minLength']}")
        if schema.get("maxLength") is not None:
            parts.append(f"max_length={schema['maxLength']}")
        if schema.get("multipleOf") is not None:
            parts.append(f"multiple_of={schema['multipleOf']}")
        if schema.get("pattern") is not None:
            parts.append(f"pattern={json.dumps(schema['pattern'])}")
        return parts


def generate_pydantic(schema_set: SchemaSet) -> str:
    return PydanticGenerator(schema_set).emit()


