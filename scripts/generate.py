class TsGenerator:
    """Generates TS type declarations from the canonical schemas."""

    def __init__(self, schema_set: SchemaSet) -> None:
        self.set = schema_set
        self.lines: list[str] = []
        self.generated: set[tuple[str, str]] = set()

    # -- type expression ----------------------------------------------------

    def type_of(self, schema_name: str, schema: dict[str, Any], indent: str) -> str:  # noqa: PLR0911
        if "$ref" in schema:
            target_name, def_name = _resolve_def_ref(self.set, schema_name, schema["$ref"])
            return f"{pascal(target_name)}.{pascal(def_name)}"
        if "oneOf" in schema:
            rendered = [
                self.type_of(target_name, {"$ref": f"#/$defs/{def_name}"}, indent)
                for target_name, def_name in _union_variants(self.set, schema_name, schema)
            ]
            return " | ".join(_dedupe(rendered))
        if "anyOf" in schema:
            rendered = []
            for sub in schema["anyOf"]:
                if "$ref" in sub:
                    target_name, def_name = _resolve_def_ref(self.set, schema_name, sub["$ref"])
                    rendered.append(f"{pascal(target_name)}.{pascal(def_name)}")
                elif "enum" in sub or "const" in sub or "type" in sub:
                    rendered.append(self.type_of(schema_name, sub, indent))
                else:
                    raise ValueError(f"unsupported anyOf variant: {json.dumps(sub)[:200]}")
            return " | ".join(_dedupe(rendered))
        if "const" in schema:
            return json.dumps(schema["const"], ensure_ascii=False)
        if "enum" in schema:
            return " | ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
        types = schema.get("type")
        if isinstance(types, list):
            return " | ".join(self._primitive(t) for t in types)
        if isinstance(types, str):
            if types == "array":
                items = schema.get("items")
                if isinstance(items, dict):
                    return f"{self.type_of(schema_name, items, indent)}[]"
                return "unknown[]"
            if types == "object" and "properties" not in schema:
                return "Record<string, unknown>"
            return self._primitive(types)
        raise ValueError(f"cannot render type for schema: {json.dumps(schema)[:200]}")

    @staticmethod
    def _primitive(type_name: str) -> str:
        return {
            "string": "string",
            "number": "number",
            "integer": "number",
            "boolean": "boolean",
            "array": "unknown[]",
            "object": "Record<string, unknown>",
            "null": "null",
        }.get(type_name, "unknown")

    # -- emission -----------------------------------------------------------

    def emit(self) -> str:
        out: list[str] = [TS_HEADER, "// prettier-ignore", ""]
        for schema_name in DOCUMENT_SCHEMAS:
            schema = self.set.schemas[schema_name]
            defs = schema.get("$defs", {})
            out.append(f"export declare namespace {pascal(schema_name)} {{")
            for def_name, def_schema in sorted(defs.items(), key=_def_sort_key):
                out.append(self._emit_def(schema_name, def_name, def_schema, "  "))
            out.append("}")
            out.append("")
        return "\n".join(out).rstrip() + "\n"

    def _emit_def(
        self, schema_name: str, def_name: str, schema: dict[str, Any], indent: str
    ) -> str:
        key = (schema_name, def_name)
        del key  # names are fully qualified by namespace; no memoization needed
        ts_name = pascal(def_name)
        doc = schema.get("description")
        lines: list[str] = []
        if doc:
            lines.append(f"{indent}/** {doc} */")
        if "const" in schema:
            lines.append(f"{indent}export type {ts_name} = {json.dumps(schema['const'])};")
            return "\n".join(lines)
        if "enum" in schema:
            values = " | ".join(json.dumps(v, ensure_ascii=False) for v in schema["enum"])
            lines.append(f"{indent}export type {ts_name} = {values};")
            return "\n".join(lines)
        if "oneOf" in schema:
            rendered = [
                f"{pascal(target_name)}.{pascal(def_name)}"
                for target_name, def_name in _union_variants(self.set, schema_name, schema)
            ]
            lines.append(f"{indent}export type {ts_name} = " + " | ".join(_dedupe(rendered)) + ";")
            return "\n".join(lines)
        fields = _object_fields(schema)
        if fields is not None:
            required_any_of = _required_any_of_groups(schema)
            declaration = "type" if required_any_of else "interface"
            operator = " =" if required_any_of else ""
            lines.append(f"{indent}export {declaration} {ts_name}{operator} {{")
            for field in fields:
                field_doc = field.schema.get("description")
                if field_doc:
                    lines.append(f"{indent}  /** {field_doc} */")
                optional = "" if field.required else "?"
                field_type = self.type_of(schema_name, field.schema, indent)
                lines.append(f"{indent}  {field.name}{optional}: {field_type};")
            lines.append(f"{indent}}}")
            if required_any_of:
                lines[-1] += " & ("
                fields_by_name = {field.name: field for field in fields}
                for group in required_any_of:
                    required_fields = "; ".join(
                        f"{name}: {self.type_of(schema_name, fields_by_name[name].schema, indent)}"
                        for name in group
                    )
                    lines.append(f"{indent}  | {{ {required_fields} }}")
                lines.append(f"{indent});")
            return "\n".join(lines)
        # type alias for constrained primitives (pattern ids, bounded numbers, ...)
        return "\n".join(
            [
                *lines,
                f"{indent}export type {ts_name} = {self.type_of(schema_name, schema, indent)};",
            ]
        )


def generate_ts(schema_set: SchemaSet) -> str:
    return TsGenerator(schema_set).emit()


